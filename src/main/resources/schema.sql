CREATE TABLE rfqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  description VARCHAR(2000),
  category_code VARCHAR(24),
  region VARCHAR(40) NOT NULL,
  status VARCHAR(12) NOT NULL,
  closes_at DATE,
  awarded_bid_id BIGINT,
  created_by VARCHAR(60)
);

CREATE TABLE rfq_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id),
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  token VARCHAR(64) NOT NULL UNIQUE,
  access_pin VARCHAR(8),
  status VARCHAR(16) NOT NULL
);

CREATE TABLE rfq_bids (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id),
  invitation_id BIGINT NOT NULL REFERENCES rfq_invitations(id),
  amount_cents BIGINT NOT NULL,
  currency VARCHAR(12) NOT NULL,
  incoterm VARCHAR(8) NOT NULL,
  notes VARCHAR(600),
  status VARCHAR(12) NOT NULL
);

CREATE TABLE rfq_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id),
